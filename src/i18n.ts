const dict: Record<Lang, Record<Key, string>> = { en, es };
let lang: Lang = 'en';

export const getLang = () => lang;
export const setLang = (l: Lang) => void (lang = l);
export const locale = () => (lang === 'es' ? 'es-ES' : 'en-US');
export const detectLang = (): Lang => (navigator.language?.toLowerCase().startsWith('es') ? 'es' : 'en');

export function t(key: Key, vars?: Record<string, string | number>): string {
  const s = dict[lang][key] ?? en[key];
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? '')) : s;
}

/** Apply translations to static markup: data-i18n="key" and data-i18n-attr="attr:key;attr:key". */
export function translateDom(root: ParentNode = document) {
  for (const n of root.querySelectorAll<HTMLElement>('[data-i18n]')) n.textContent = t(n.dataset.i18n as Key);
  for (const n of root.querySelectorAll<HTMLElement>('[data-i18n-attr]')) {
    for (const pair of n.dataset.i18nAttr!.split(';')) {
      const [attr, key] = pair.split(':');
      n.setAttribute(attr, t(key as Key));
    }
  }
}
